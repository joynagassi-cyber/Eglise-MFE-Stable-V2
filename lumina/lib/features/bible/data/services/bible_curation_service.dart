import 'package:flutter_riverpod/flutter_riverpod.dart';

/// Service gérant les versets "Pilliers de la Foi" (Curated Verses)
class BibleCurationService {
  BibleCurationService._();

  /// Liste des versets clés (Pilliers de la Foi)
  /// Format: 'BOOK_ID:CHAPTER:VERSE'
  static const Set<String> _keyVerses = {
    'GEN:1:1', // Au commencement...
    'PSA:23:1', // L'Éternel est mon berger...
    'ISA:9:6', // Car un enfant nous est né...
    'ISA:53:5', // Mais il était blessé pour nos péchés...
    'MAT:5:3', // Heureux les pauvres en esprit...
    'MAT:6:33', // Cherchez premièrement le royaume...
    'MAT:28:19', // Allez, faites de toutes les nations des disciples...
    'JHN:1:1', // Au commencement était la Parole...
    'JHN:3:16', // Car Dieu a tant aimé le monde...
    'JHN:14:6', // Je suis le chemin, la vérité, et la vie...
    'ROM:3:23', // Car tous ont péché...
    'ROM:8:1', // Il n'y a donc maintenant aucune condamnation...
    'ROM:8:28', // Toutes choses concourent au bien...
    'ROM:10:9', // Si tu confesses de ta bouche...
    'ROM:12:1', // Je vous exhorte donc, frères...
    '1CO:13:13', // Maintenant donc ces trois choses demeurent...
    '2CO:5:17', // Si quelqu'un est en Christ...
    'GAL:2:20', // J'ai été crucifié avec Christ...
    'EPH:2:8', // Car c'est par la grâce...
    'PHP:4:13', // Je puis tout par celui qui me fortifie...
    '2TI:1:7', // Car ce n'est pas un esprit de timidité...
    'HEB:11:1', // Or la foi est une ferme assurance...
    'REV:3:20', // Voici, je me tiens à la porte...
    'REV:21:4', // Il essuiera toute larme...
  };

  /// Vérifie si un verset est un "Pillier de la Foi"
  static bool isKeyVerse(String bookId, int chapter, int verse) {
    final key = '${bookId.toUpperCase()}:$chapter:$verse';
    return _keyVerses.contains(key);
  }
}

final bibleCurationServiceProvider = Provider((ref) => BibleCurationService);